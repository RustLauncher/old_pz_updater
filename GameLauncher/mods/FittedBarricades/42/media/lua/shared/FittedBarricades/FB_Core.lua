-- Shared core: the stack a big opening's barricade is, and which fitted
-- sprite each layer of it should wear.
--
-- A barricade is an IsoBarricade world object holding at most four
-- planks, one metal sheet or one set of bars (IsoBarricade.MAX_PLANKS
-- and the private health slots are hard limits; the only setters Lua
-- can reach clamp to vanilla's maxima). So on a big opening the mod
-- barricades with a STACK of them: several IsoBarricade objects on the
-- same square facing the same way, added one after the other as the
-- player nails on more than one object holds (FB_Build.lua). Every one
-- is a stock object with stock health, save format and MP sync. Java
-- consults the square's special objects in order (GetBarricadeOnSquare
-- returns the first, the vision test asks every one), so the FIRST
-- layer - the oldest - is the one zombies thump and the player
-- unbarricades, and when it is gone the next takes over; the opening
-- stays barricaded until every layer is.
--
-- Java picks each layer's sprite from its own state (chooseSprite) every
-- time that state changes, and never writes it to a save. The mod
-- computes, for the layer's stack and the opening it is nailed to, the
-- fitted sprite of the WHOLE stack (n of P planks, m of M sheets with d
-- damaged, k of B bar sets) and, on the rendering side only, puts it on
-- the first layer and a blank tile on the others (FB_Client.lua).
-- Nothing about the art is placed, synced or saved.
--
-- Which openings count as "big" comes from FittedBarricades.MAP
-- (FB_Map.lua, generated by scripts/build_assets.py from the same
-- measurement the art was built from): window sprite name -> size
-- class, every window state included. Doors are one class (DOOR_CLASS,
-- the whole door opening), whether map door or player-built. A class
-- carries its CAPACITY - planks, sheets, bar sets - and where its tile
-- block sits (FB.CLASSES).
--
-- The class a window is MAPPED to is measured from its sprite alone.
-- Map makers also stack wall overlays on the square (plinths, kneewall
-- panels, fascias, sign bands) which the cell loader draws under the
-- barricade; where one paints a solid band across the wall it hides
-- part of the glass, and FB.windowClass clips the mapped box by the
-- bands on the square and picks the largest class in the same column
-- that fits the glass left showing (the Fitted Sheets rule). Nothing
-- fits -> the mapped class.

require "FittedBarricades/FB_Map"
require "FittedBarricades/FB_Overlays"

FittedBarricades = FittedBarricades or {}
local FB = FittedBarricades

FB.DIR = { W = 0, E = 1, N = 2, S = 3 }
FB.KIND = { planks = "planks", metal = "metal", bars = "bars" }
FB.KINDS = { FB.KIND.planks, FB.KIND.metal, FB.KIND.bars }

-- The three barricade build recipes, by kind: the item one adds, the
-- entity sprite the build cursor shows for it (the tile vanilla's
-- context menu hands ISWorldObjectContextMenu.onBarricade) and that
-- menu option's text and icon.
FB.RECIPE = {
	planks = { item = "Base.Plank", tile = "carpentry_01_8", text = "ContextMenu_Barricade", icon = "Item_Plank" },
	metal = { item = "Base.SheetMetal", tile = "constructedobjects_01_24", text = "ContextMenu_MetalBarricade", icon = "Item_SheetMetal" },
	bars = { item = "Base.MetalBar", tile = "constructedobjects_01_55", text = "ContextMenu_MetalBarBarricade", icon = "Item_SteelRod_Full" },
}

-- The recipe an entity sprite belongs to: the faces of
-- entity_barricade_planks / metalsheet / metalbar.
FB.recipeKind = function(spriteName)
	if not spriteName then return nil end
	if luautils.stringStarts(spriteName, "carpentry_01_") then return FB.KIND.planks end
	local n = tonumber(string.match(spriteName, "^constructedobjects_01_(%d+)$"))
	if n and n >= 24 and n <= 31 then return FB.KIND.metal end
	if n and n >= 52 and n <= 55 then return FB.KIND.bars end
	return nil
end

-- Sprite name of a class / variant index / direction: the class's tile
-- block starts at `base` in tileset `ts`, variant-major (make_art.py).
FB.tileName = function(class, vi, dir)
	local c = FB.CLASSES[class]
	return string.format("%s_%02d_%d", FB.PREFIX, c.ts, c.base + vi * 4 + dir)
end

-- Position of a stack state in a class's variant list: planks1..P,
-- then metal m = 1..M with d = 0..m damaged, then bars1..B (make_art.py
-- variants()). Counts past the capacity draw the full barricade.
FB.variantIndex = function(c, state)
	if state.kind == FB.KIND.planks then
		return math.min(state.planks, c.planks) - 1
	end
	if state.kind == FB.KIND.metal then
		local m = math.min(state.sheets, c.metal)
		local d = math.min(state.damaged, m)
		return c.planks + math.floor((m - 1) * (m + 2) / 2) + d
	end
	return c.planks + math.floor(c.metal * (c.metal + 3) / 2) + math.min(state.sets, c.bars) - 1
end

-- The object's sprite name, nil when it has no sprite.
FB.spriteName = function(obj)
	local sprite = obj and obj:getSprite()
	return sprite and sprite:getName() or nil
end

FB.isOurSprite = function(name)
	return name ~= nil and luautils.stringStarts(name, FB.PREFIX .. "_")
end

-- Direction index of a barricade from the IsoDirections it was added
-- with (W/N on the opening's own square, E/S on the far square).
FB.dirIndex = function(barricade)
	local dir = barricade:getDir()
	if dir == IsoDirections.W then return FB.DIR.W end
	if dir == IsoDirections.E then return FB.DIR.E end
	if dir == IsoDirections.N then return FB.DIR.N end
	if dir == IsoDirections.S then return FB.DIR.S end
	return nil
end

-- ------------------------------------------------------------- stacks

-- The layers of one side of an opening: every IsoBarricade on `square`
-- facing `dir`, in special-object order - the order Java consults them
-- (the first is the one zombies thump and the player removes from).
-- Filled into `out` when given (a caller's scratch table, refilled
-- every tick without a new one), else a new table.
FB.layers = function(square, dir, out)
	out = out or {}
	local n = 0
	if square then
		local specials = square:getSpecialObjects()
		for i = 0, specials:size() - 1 do
			local obj = specials:get(i)
			if instanceof(obj, "IsoBarricade") and obj:getDir() == dir then
				n = n + 1
				out[n] = obj
			end
		end
	end
	for i = #out, n + 1, -1 do out[i] = nil end
	return out
end

-- The stack a barricade belongs to.
FB.stackOf = function(barricade)
	return FB.layers(barricade:getSquare(), barricade:getDir())
end

-- What one layer holds: its kind (planks / metal / bars, nil when
-- empty), its plank count, and whether its sheet is damaged - below
-- half its health, the sprite's own threshold
-- (IsoBarricade.chooseSprite: metalHealth <= 2500 of 5000).
FB.layerState = function(b)
	if b:isMetal() then return FB.KIND.metal, 0, b:getThumpCondition() <= 0.5 end
	if b:isMetalBar() then return FB.KIND.bars, 0, false end
	local n = b:getNumPlanks()
	if n > 0 then return FB.KIND.planks, n, false end
	return nil, 0, false
end

-- What a stack holds, summed over its layers of the stack's kind (the
-- first non-empty layer's; a stack is never mixed - FB.canAdd forbids
-- it): { kind, planks, sheets, damaged, sets }. nil for a stack with
-- nothing in it.
FB.stackState = function(layers)
	local state = nil
	for _, b in ipairs(layers) do
		local kind, n, damaged = FB.layerState(b)
		if kind then
			if not state then
				state = { kind = kind, planks = 0, sheets = 0, damaged = 0, sets = 0 }
			end
			if kind == state.kind then
				if kind == FB.KIND.planks then
					state.planks = state.planks + n
				elseif kind == FB.KIND.metal then
					state.sheets = state.sheets + 1
					if damaged then state.damaged = state.damaged + 1 end
				else
					state.sets = state.sets + 1
				end
			end
		end
	end
	return state
end

-- Whether one more object of `kind` (a plank, a sheet, a set of bars)
-- fits on a stack for a class: the stack is empty or of that kind, and
-- holds fewer than the class's capacity.
FB.canAdd = function(layers, class, kind)
	local c = FB.CLASSES[class]
	if not c then return false end
	local state = FB.stackState(layers)
	if state and state.kind ~= kind then return false end
	if kind == FB.KIND.planks then return (state and state.planks or 0) < c.planks end
	if kind == FB.KIND.metal then return (state and state.sheets or 0) < c.metal end
	return (state and state.sets or 0) < c.bars
end

-- A number for a stack's state, to notice a change between ticks
-- without recomputing the sprites (and without building a string every
-- tick): per layer its kind, whether its sheet is damaged and its plank
-- count (at most IsoBarricade.MAX_PLANKS = 4) in six bits, the layers
-- folded in order - exact in a double for far more layers than any
-- class holds.
local KIND_CODE = { [FB.KIND.planks] = 1, [FB.KIND.metal] = 2, [FB.KIND.bars] = 3 }
FB.signature = function(layers)
	local sig = 0
	for _, b in ipairs(layers) do
		local kind, n, damaged = FB.layerState(b)
		sig = sig * 64 + (kind and KIND_CODE[kind] or 0) * 16 + (damaged and 8 or 0) + n
	end
	return sig
end

-- -------------------------------------------------------------- order

-- B42 draws a square's translucent objects - the window, its curtain,
-- a canopy or awning hung on the wall (walls_decoration_01_112..123)
-- and every barricade tile, vanilla's and ours (tileGeometry.txt marks
-- them Translucent) - in a pass of their own after the opaque one,
-- with depth WRITES off (FBORenderCell.renderOneChunk_Translucent:
-- glDepthMask(false)). Each is depth-tested against the opaque scene
-- only; between two translucent objects on one square the one later
-- in the square's object list paints over the earlier, whatever their
-- depth textures say. IsoBarricade.AddBarricadeToObject puts a new
-- barricade in front of the facing's curtain, else at the END of the
-- list - after a canopy the map hung over the same window - so the
-- barricade paints over the canopy. Vanilla's tile is a band across
-- the middle of the window and rarely reaches the canopy; a fitted one
-- covers the whole opening and does.
--
-- On the opening's own square (the near side, W/N) the right order is
-- the opening, then its layers, then the rest: nothing on that square
-- hangs behind the wall plane but the wall and the opening in it, and
-- everything else there - curtain, canopy, a fading object - is in
-- front of the wall, and of a barricade on it. So the layers go
-- straight after the opening, in stack order. The far side (E/S, the
-- square beyond) keeps vanilla's rule: its barricade is the nearest
-- thing to the camera on its square.
--
-- The object list's order is what saves and what MP packets address
-- objects by (RemoveItemFromSquarePacket, ObjectChangePacket: square
-- plus index), so it is only changed where every copy of the square
-- follows: in singleplayer (FB_Client.lua, on every fit), on the MP
-- server before a square reaches a client (FB_Build.lua: a square
-- streaming in, a layer built and not yet transmitted), never on an
-- MP client, which draws the list in the order the server sent.

local function indexIn(objects, obj)
	for i = 0, objects:size() - 1 do
		if objects:get(i) == obj then return i end
	end
	return -1
end

-- Move the object at `from` to `to` (indices of the object list),
-- shifting the ones between - with set() alone: PZArrayList's add and
-- remove are each overloaded on an index and an object, set is not.
local function moveObject(objects, from, to)
	local obj = objects:get(from)
	if from < to then
		for i = from, to - 1 do objects:set(i, objects:get(i + 1)) end
	else
		for i = from, to + 1, -1 do objects:set(i, objects:get(i - 1)) end
	end
	objects:set(to, obj)
end

-- Put a near side's layers straight after their opening in the
-- square's object list, in the order given (the stack's). Nothing for
-- a far side (the opening is on another square) or an opening missing
-- from the list. Returns true when something moved.
FB.orderLayers = function(square, opening, layers)
	if not square or not opening or opening:getSquare() ~= square then return false end
	local objects = square:getObjects()
	local at = indexIn(objects, opening)
	if at < 0 then return false end
	local moved = false
	for _, layer in ipairs(layers) do
		local from = indexIn(objects, layer)
		if from >= 0 then
			-- a layer taken out from before the cursor shifts the cursor,
			-- and the slot after it, down by one
			local want = from < at and at or at + 1
			if from ~= want then
				moveObject(objects, from, want)
				moved = true
			end
			at = want
		end
	end
	return moved
end

-- The object-list index a NEW layer of a near side goes in at: after
-- the last of the opening and the layers already there. nil for a far
-- side, or an opening missing from the list (vanilla's rule stands).
FB.nearIndex = function(square, opening, layers)
	if not square or not opening or opening:getSquare() ~= square then return nil end
	local objects = square:getObjects()
	local last = indexIn(objects, opening)
	if last < 0 then return nil end
	for _, layer in ipairs(layers) do
		local i = indexIn(objects, layer)
		if i > last then last = i end
	end
	return last + 1
end

-- Order every fitted side on a square: the sides whose first layer's
-- opening has a size class (a far side's opening may not be loaded
-- yet; it is on another square and is not ordered anyway).
FB.orderSquare = function(square)
	if not square then return end
	local specials = square:getSpecialObjects()
	local seen = {}
	for i = 0, specials:size() - 1 do
		local obj = specials:get(i)
		if instanceof(obj, "IsoBarricade") and not seen[obj:getDir()] then
			seen[obj:getDir()] = true
			local layers = FB.layers(square, obj:getDir())
			local opening = layers[1]:getBarricadedObject()
			if opening and FB.targetClass(opening) ~= nil then
				FB.orderLayers(square, opening, layers)
			end
		end
	end
end

-- ------------------------------------------------------------ classes

-- Rows a barricade may stop short of the glass, or run past it onto an
-- overlay band, and still count as fitting.
FB.CLIP_TOL = 12

-- Names of every overlay sprite on the opening's square: the attached
-- sprites of every object there and, for a square with nothing to hang
-- it on, the plain object it becomes.
local function squareOverlays(sq)
	local names = {}
	local objects = sq:getObjects()
	for i = 0, objects:size() - 1 do
		local obj = objects:get(i)
		local name = FB.spriteName(obj)
		if name and FB.OVERLAYS[name] then names[name] = true end
		local attached = obj:getAttachedAnimSprite()
		if attached then
			for j = 0, attached:size() - 1 do
				local inst = attached:get(j)
				name = inst and inst:getName()
				if name and FB.OVERLAYS[name] then names[name] = true end
			end
		end
	end
	return names
end

-- Class for a WINDOW-like opening (IsoWindow, IsoWindowFrame, a
-- player-built IsoThumpable window): its mapped class, clipped by the
-- overlay bands on its square. nil when the vanilla barricade already
-- covers it.
FB.windowClass = function(window)
	local base = FB.MAP[FB.spriteName(window) or ""]
	if base == nil then return nil end
	local box = FB.CLASSES[base]
	local sq = window:getSquare()
	if not box or box.stack ~= "" or not sq then return base end
	local face = window:getNorth() and "N" or "W"
	local top, bottom = box.top, box.bottom
	for name in pairs(squareOverlays(sq)) do
		local band = FB.OVERLAYS[name]
		if band.face == face then
			if band.top and band.top > top then top = band.top end
			if band.bottom and band.bottom < bottom then bottom = band.bottom end
		end
	end
	if top - box.top <= FB.CLIP_TOL and box.bottom - bottom <= FB.CLIP_TOL then
		return base
	end
	local best, bestLen
	for c = 0, FB.N_CLASSES - 1 do
		local cb = FB.CLASSES[c]
		if cb.x == box.x and cb.stack == "" and cb.top >= top - FB.CLIP_TOL
				and cb.bottom <= bottom + FB.CLIP_TOL then
			local len = cb.bottom - cb.top
			if not best or len > bestLen then best, bestLen = c, len end
		end
	end
	return best or base
end

-- Whether a world object is an opening a barricade may go on: a map
-- door, window or window frame that allows it, or a player-built
-- (IsoThumpable) door or window that does - the test vanilla's
-- barricade recipe makes (buildRecipeCode.lua OnIsValid).
FB.isOpening = function(o)
	if instanceof(o, "IsoThumpable") then
		return (o:isDoor() or o:isWindow()) and o:getCanBarricade()
	end
	return (instanceof(o, "IsoDoor") or instanceof(o, "IsoWindow") or instanceof(o, "IsoWindowFrame"))
		and o:isBarricadeAllowed()
end

-- Whether an opening is a door, map or player-built.
FB.isDoor = function(o)
	return instanceof(o, "IsoDoor") or (instanceof(o, "IsoThumpable") and o:isDoor())
end

-- Class of the opening a barricade is nailed to: doors (map doors and
-- player-built ones; double and garage doors cannot be barricaded)
-- are DOOR_CLASS, everything else goes by its window sprite. nil for
-- an opening the vanilla barricade covers, or none at all.
FB.targetClass = function(barricadeAble)
	if not barricadeAble then return nil end
	if FB.isDoor(barricadeAble) then return FB.DOOR_CLASS end
	return FB.windowClass(barricadeAble)
end

-- ------------------------------------------------------------ sprites

-- The sprite each layer of a stack should wear, by layer index: the
-- first layer the art of the whole stack, every other layer the blank
-- tile. nil (keep whatever they have: the vanilla sprites) for a stack
-- on a small opening (no class), with nothing in it, or facing nowhere.
FB.stackSprites = function(layers, class)
	if class == nil or #layers == 0 then return nil end
	local dir = FB.dirIndex(layers[1])
	if dir == nil then return nil end
	local state = FB.stackState(layers)
	if state == nil then return nil end
	local out = { FB.tileName(class, FB.variantIndex(FB.CLASSES[class], state), dir) }
	for i = 2, #layers do out[i] = FB.BLANK[dir + 1] end
	return out
end

-- Put the sprite `want` (one of FB.stackSprites) on the barricade if it
-- is not wearing it. setSpriteFromName resolves through the sprite
-- manager (the tileset sprite with its id and depth), never a bare
-- texture. Returns true when the sprite changed.
FB.apply = function(barricade, want)
	if FB.spriteName(barricade) == want then return false end
	barricade:setSpriteFromName(want)
	return true
end
