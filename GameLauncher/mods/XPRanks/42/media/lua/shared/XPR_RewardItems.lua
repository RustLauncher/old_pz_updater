local SKILL_VHS_PREFIX = "XPR_SKILL_VHS:"
local HOME_VHS_PREFIX = "XPR_HOME_VHS:"
local RETAIL_VHS_PREFIX = "XPR_RETAIL_VHS:"
local ALL_VHS_PREFIXES = { SKILL_VHS_PREFIX, HOME_VHS_PREFIX, RETAIL_VHS_PREFIX }

local function matchVhsPrefix(id)
	if type(id) ~= "string" then return nil end
	for _, prefix in ipairs(ALL_VHS_PREFIXES) do
		if id:sub(1, #prefix) == prefix then return prefix end
	end
	return nil
end

function XPR_RewardItems.isSkillVhs(id)
	return matchVhsPrefix(id) ~= nil
end

function XPR_RewardItems.getSkillVhsIndex(id)
	local prefix = matchVhsPrefix(id)
	if not prefix then return nil end
	return tonumber(id:sub(#prefix + 1))
end

function XPR_RewardItems.buildSkillVhsId(entry)
	local prefix
	if entry.hasSkillCode then
		prefix = SKILL_VHS_PREFIX
	elseif entry.category == "Home-VHS" then
		prefix = HOME_VHS_PREFIX
	else
		prefix = RETAIL_VHS_PREFIX
	end
	return prefix .. tostring(entry.index)
end

local SKILL_VHS_CATEGORY_FULLTYPE = {
	["Retail-VHS"] = "Base.VHS_Retail",
	["Home-VHS"] = "Base.VHS_Home",
}

local skillVhsEntriesCache = nil

function XPR_RewardItems.getSkillVhsEntries()
	if skillVhsEntriesCache then return skillVhsEntriesCache end

	local entries = {}
	local radio = getZomboidRadio and getZomboidRadio()
	local recordedMedia = radio and radio:getRecordedMedia()
	if recordedMedia then
		for category in pairs(SKILL_VHS_CATEGORY_FULLTYPE) do
			local list = recordedMedia:getAllMediaForCategory(category)
			if list then
				for i = 0, list:size() - 1 do
					local md = list:get(i)
					if md then
						local hasSkillCode = false
						for j = 0, md:getLineCount() - 1 do
							local line = md:getLine(j)
							local codes = line and line:getCodes()
							if codes and codes ~= "" and not codes:find("^BOR") then
								hasSkillCode = true
								break
							end
						end
						entries[#entries + 1] = {
							index = md:getIndex(),
							title = md:getTranslatedItemDisplayName(),
							category = category,
							hasSkillCode = hasSkillCode,
						}
					end
				end
			end
		end
	end

	skillVhsEntriesCache = entries
	return entries
end

function XPR_RewardItems.getDefaultSkillVhsIds()
	local ids = {}
	for _, entry in ipairs(XPR_RewardItems.getSkillVhsEntries()) do
		if entry.hasSkillCode then
			ids[#ids + 1] = XPR_RewardItems.buildSkillVhsId(entry)
		end
	end
	return ids
end

function XPR_RewardItems.getSkillVhsEntry(index)
	if not index then return nil end
	for _, entry in ipairs(XPR_RewardItems.getSkillVhsEntries()) do
		if entry.index == index then return entry end
	end
	return nil
end

function XPR_RewardItems.getDefaultSkillVhsTier(id)
	local entry = XPR_RewardItems.getSkillVhsEntry(XPR_RewardItems.getSkillVhsIndex(id))
	if not entry or not entry.hasSkillCode then return nil end
	if entry.category == "Home-VHS" then return "RARE" end
	return "UNCOMMON"
end

function XPR_RewardItems.getSkillVhsFullType(id)
	local entry = XPR_RewardItems.getSkillVhsEntry(XPR_RewardItems.getSkillVhsIndex(id))
	return entry and SKILL_VHS_CATEGORY_FULLTYPE[entry.category]
end

function XPR_RewardItems.getSkillVhsDisplayName(id)
	local entry = XPR_RewardItems.getSkillVhsEntry(XPR_RewardItems.getSkillVhsIndex(id))
	return (entry and entry.title) or id
end

