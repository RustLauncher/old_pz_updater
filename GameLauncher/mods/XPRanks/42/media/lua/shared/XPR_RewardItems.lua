local function parseRecipeItem(id)
	if not XPR_RewardItems.isRecipeItem(id) then return nil, nil end
	local rest = id:sub(#RECIPE_SENTINEL_PREFIX + 1)
	local tag, recipeId = rest:match("^([^:]+):(.+)$")
	return tag, recipeId
end

