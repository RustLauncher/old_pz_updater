	for _, id in ipairs(XPR_RewardItems.COMMON or {}) do map[id] = { tier = "COMMON", active = true } end
	for _, id in ipairs(XPR_RewardItems.UNCOMMON or {}) do map[id] = { tier = "UNCOMMON", active = true } end
	for _, id in ipairs(XPR_RewardItems.RARE or {}) do map[id] = { tier = "RARE", active = true } end
	return map
end

