local filteredCache = {}

local function hasIcon(itemId)
	if XPR_RewardItems.isXpBonus(itemId) then return true end

	if XPR_RewardItems.isSkillVhs(itemId) then return true end

	if XPR_RewardItems.isRecipeItem(itemId) then return true end

	local scriptItem = ScriptManager.instance and ScriptManager.instance:getItem(itemId)
	if not scriptItem then return false end

	if scriptItem.getIconsForTexture then
		local variants = scriptItem:getIconsForTexture()
		if variants and not variants:isEmpty() then
			return true
		end
	end

	local icon = scriptItem.getIcon and scriptItem:getIcon()
	return icon ~= nil and icon ~= "" and icon ~= "None"
end

function XPR_RewardItems.getValidPool(band)
	if filteredCache[band] then return filteredCache[band] end

	local source = XPR_RewardItems[band]
	local filtered = {}
	if source then
		for _, id in ipairs(source) do
			if hasIcon(id) then
				filtered[#filtered + 1] = id
			end
		end
	end

	filteredCache[band] = filtered
	return filtered
end

XPR_RewardItems._clientSyncedPool = nil

function XPR_RewardItems.getEffectivePool(band)
	local source
	if XPR_RewardConfigStore and XPR_RewardConfigStore.getPool then
		source = XPR_RewardConfigStore.getPool(band)
	elseif XPR_RewardItems._clientSyncedPool and XPR_RewardItems._clientSyncedPool[band] then
		source = XPR_RewardItems._clientSyncedPool[band]
	else
		source = XPR_RewardItems[band]
	end

	local filtered = {}
	for _, id in ipairs(source or {}) do
		if hasIcon(id) then
			filtered[#filtered + 1] = id
		end
	end
	XPR_dprint("[XPR] getEffectivePool(" .. band .. "): " .. #filtered .. "/" .. #(source or {}) .. " items passed hasIcon filter")
	return filtered
end

function XPR_RewardItems.applySyncedConfig(itemsMap)
	local buckets = { COMMON = {}, UNCOMMON = {}, RARE = {} }
	if itemsMap then
		for id, entry in pairs(itemsMap) do
			if entry and buckets[entry.tier] and entry.active ~= false then
				buckets[entry.tier][#buckets[entry.tier] + 1] = id
			end
		end
	end
	XPR_RewardItems._clientSyncedPool = buckets
	XPR_RewardItems._clientSyncedItemsMap = itemsMap or {}
end

