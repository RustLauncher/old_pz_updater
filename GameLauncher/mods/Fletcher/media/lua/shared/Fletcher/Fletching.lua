--[[
    Fletcher: what an arrow or bolt is fletched with (docs/urban_crafting.md, option A).

    An arrow item keeps its fletching in mod data: md.fl_fletch = "plastic/<colour>" or "tape"; none means
    feathers (every arrow made before this, and every arrow fletched with feathers). Arrow item types stay
    one per head (plus matched), so quivers, the arrow radial and "best arrow" picking work as before.

    The fletching travels with the arrow as one short code, `fl` (nil = feathers), beside the arrow type:
    nocked (bow md.fl_nockedFletch, Reload.lua), in the shot record and the projectile (shot.fl / p.fl),
    in multiplayer messages (m.fl), in stuck-arrow records (a.fl), and back onto every arrow item made
    from a shot (F.setFletch). A damaged arrow has lost its fletching (it is re-fletched), so it has none.

    Kinds (F.FLETCH): multipliers on the arrow's own spread, break chance and wear (the chance a surviving
    arrow comes back damaged); `bench` = may go into a matched set at the Fletcher's Bench.
]]

require "Fletcher/Core"
require "Fletcher/FletchLooks"     -- (F.FLETCH_LOOK: GENERATED by animation/scripts/fletch_looks.py)
local F = Fletcher

F.FLETCH = {
    feather = { spread = 1.00, breakage = 1.00, wear = 1.00, bench = true },
    plastic = { spread = 1.05, breakage = 0.85, wear = 0.60, bench = true },    -- stiff vanes: last, steer a hair less
    tape    = { spread = 1.15, breakage = 1.00, wear = 1.60, bench = false },   -- the quick emergency job
}
-- plastic vane colours (one per craft, random): a model / icon variant each
F.VANE_COLORS = { "orange", "green", "yellow", "pink", "blue" }
-- the fletching items (tag fletcher:fletching): which kind each one puts on an arrow
F.FLETCH_ITEMS = {
    ["Fletcher.Fletching"] = "feather",
    ["Fletcher.PlasticVanes"] = "plastic",
    ["Fletcher.TapeVanes"] = "tape",
}

--- (kind, colour) of a fletching code; nil / "" / "feather" = feathers
function F.fletchParts(fl)
    if fl == nil or fl == "" or fl == "feather" then return "feather", nil end
    local kind, color = string.match(fl, "^(%a+)/?(%a*)$")
    if not kind or not F.FLETCH[kind] then return "feather", nil end
    return kind, (color ~= "" and color or nil)
end

--- A code from a kind (and colour): nil for feathers, "tape", "plastic/orange"
function F.fletchCode(kind, color)
    if kind == nil or kind == "feather" or not F.FLETCH[kind] then return nil end
    if kind == "plastic" then return "plastic/" .. (color or F.VANE_COLORS[1]) end
    return kind
end

--- The fletching definition (multipliers) of a code
function F.fletchDef(fl)
    return F.FLETCH[(F.fletchParts(fl))] or F.FLETCH.feather
end

--- A random plastic vane colour
function F.randomVaneColor()
    return F.VANE_COLORS[ZombRand(#F.VANE_COLORS) + 1]
end

--- The fletching code of an arrow item (nil = feathers)
function F.fletchOf(item)
    if not item or not item.getModData then return nil end
    local fl = item:getModData().fl_fletch
    if fl == nil or fl == "" then return nil end
    return fl
end

--- Put a fletching on an arrow item (nil = feathers) and update its look. Returns the item.
function F.setFletch(item, fl)
    if not item or not item.getModData then return item end
    local kind = F.fletchParts(fl)
    item:getModData().fl_fletch = (kind ~= "feather") and fl or nil
    if F.refreshArrowLook then F.refreshArrowLook(item) end
    return item
end

--- Name, icon and model of an arrow item for its fletching: "Stone Arrow (plastic vanes)", and the
--- variant icon / ground model of F.FLETCH_LOOK (FletchLooks.lua). Not kept by a save: re-applied when
--- an inventory is shown or a square loads (client/Fletcher/FletchLookRefresh.lua).
F.FLETCH_LOOK = F.FLETCH_LOOK or {}
function F.refreshArrowLook(item)
    if not item or not item.getFullType then return end
    local kind, color = F.fletchParts(F.fletchOf(item))
    local base = getItemNameFromFullType(item:getFullType())
    if kind == "feather" then
        if item:isCustomName() then item:setName(base); item:setCustomName(false) end
    else
        item:setName(base .. " (" .. getText("IGUI_Fletcher_Fletch_" .. kind) .. ")")
        item:setCustomName(true)
    end
    local looks = F.FLETCH_LOOK[item:getFullType()]
    local look = looks and looks[kind == "plastic" and ("plastic/" .. (color or F.VANE_COLORS[1])) or kind]
    local script = item:getScriptItem()
    -- feathers (or no variant): the arrow's own icon and model back
    local icon = look and look.icon or (script and script:getIcon())
    local model = look and look.model or (script and script:getWorldStaticModel())
    local tex = icon and F.iconTexture(icon)
    if tex and item:getTexture() ~= tex then item:setTexture(tex) end
    if model and item.setWorldStaticModel and item:getWorldStaticModel() ~= model then item:setWorldStaticModel(model) end
end

--- An item icon by name (mod textures loose in media/textures aren't always registered by short name)
function F.iconTexture(name)
    return getTexture("Item_" .. name) or getTexture("media/textures/Item_" .. name .. ".png")
end

--- Is this a fletching item, and which kind?
function F.fletchKindOfItem(item)
    return item and item.getFullType and F.FLETCH_ITEMS[item:getFullType()] or nil
end

local function list(jl)
    local out = {}
    for i = 0, (jl and jl:size() or 0) - 1 do table.insert(out, jl:get(i)) end
    return out
end

--- The fletching kind a craft used: the most common fletching item among what it consumed (a bench
--- set takes five), nil when none went in
function F.fletchKindUsed(items)
    local n, best, bestN = {}, nil, 0
    for _, it in ipairs(items) do
        local k = F.fletchKindOfItem(it)
        if k then
            n[k] = (n[k] or 0) + 1
            if n[k] > bestN then best, bestN = k, n[k] end
        end
    end
    return best
end

F.OnCreate = F.OnCreate or {}

--- Fletch / re-fletch / bench recipes: every arrow made gets the fletching that went in (a plastic set
--- shares one random colour). Wrapped stably at the end of Seasoning.lua, like the other hooks.
function F.OnCreate.fletchArrow(data, character)
    local used = list(data:getAllConsumedItems())
    local kind = F.fletchKindUsed(used)
    local fl = F.fletchCode(kind, kind == "plastic" and F.randomVaneColor() or nil)
    if not kind then
        -- no fletching went in (a fire arrow from an arrow): it keeps the arrow's own
        for _, it in ipairs(used) do
            if F.ARROW_DEFS and F.ARROW_DEFS[it:getFullType()] then fl = F.fletchOf(it); break end
        end
    end
    for _, it in ipairs(list(data:getAllCreatedItems())) do
        if F.ARROW_DEFS == nil or F.ARROW_DEFS[it:getFullType()] then
            F.setFletch(it, fl)
            if isServer() and syncItemModData then pcall(syncItemModData, character, it) end
        end
    end
end

return F
