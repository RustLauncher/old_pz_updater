-- Shared core: re-skinning vanilla window sheets on big windows.
--
-- The mod never places a sheet itself. Vanilla's own IsoWindow.addSheet
-- does everything it always does - side pick, occupancy guard, sheet
-- consumption, MP transmit - and the mod only REPLACES the resulting
-- IsoCurtain's sprite when the window is big: remove the half-tile
-- curtain from its slot, put an identical curtain wearing the fitted
-- fittedsheets_01 sprite in the same slot, same open/closed state. One
-- mechanism serves every path a vanilla sheet can appear through: the
-- add-sheet timed action (wrapped in FT_AddSheet.lua), pre-mod sheets
-- caught on square load and world-gen sheets caught on chunk load
-- (FT_Server.lua).
--
-- Everything else is stock engine behavior on a stock IsoCurtain:
-- open/close click handling, vision blocking, the obscuring fade (the
-- curtain delegates to its window via getObjectAttachedTo), removal
-- refunding Base.Sheet, save/load and MP sync. The tile properties are
-- copied verbatim from the vanilla sheet tiles, so nothing anywhere in
-- the engine can tell the difference except the art. The one thing
-- done differently from vanilla is WHERE in the square's object list a
-- near-slot sheet goes (FT.orderNear, below): straight after its
-- window rather than at the end, so the furniture in front of the
-- window paints over the sheet instead of under it.
--
-- Which windows count as "big" comes from FittedSheets.MAP
-- (FT_WindowMap.lua, generated by scripts/build_assets.py from the same
-- measurement the art was built from): window sprite name -> size class,
-- every window state (closed/open/smashed/glass removed) included.
--
-- The class a window is MAPPED to is measured from its sprite alone.
-- Map makers also stack wall overlays on the square (plinths, kneewall
-- panels, fascias, sign bands), which the cell loader attaches to the
-- wall - or to the window itself on a wall-less storefront square - and
-- draws under the curtain. Where such an overlay paints a solid band
-- across the wall it hides the glass beneath, and the mapped sheet
-- would drape over it. FT.sheetClass therefore clips the mapped class
-- box by the bands on the square (FittedSheets.OVERLAYS, generated) and
-- hangs the largest existing class that fits the glass left showing,
-- within CLIP_TOL rows at either end. Nothing fits -> the mapped class,
-- so a decorated window is never worse off than before.

require "FittedSheets/FT_WindowMap"
require "FittedSheets/FT_Overlays"

FittedSheets = FittedSheets or {}
local FT = FittedSheets

FT.TILESET = "fittedsheets_01"

-- The argument IsoGridSquare.getWindow takes for a north (true) or west
-- (false) edge. 42.21 replaced getWindow(boolean) with an overload taking
-- a GridSquareEdgeFacingDirection (a boolean no longer matches any
-- overload); 42.20 has only the boolean one.
FT.edgeFacing = function(north)
	local dir = GridSquareEdgeFacingDirection
	if not dir then return north end
	return north and dir.NORTH_SOUTH or dir.EAST_WEST
end

-- Tile layout: class c owns tiles c*8 .. c*8+7; within a block, +0..+3 are
-- the closed W/E/N/S sprites and +4..+7 the open ones. IsoCurtain resolves
-- its closed sprite as open index - 4 (a flat offset), so the constructor
-- is always handed the OPEN sprite.
local EDGE_IDX = { W = 0, E = 1, N = 2, S = 3 }

FT.openSprite = function(class, letter)
	return FT.TILESET .. "_" .. (class * 8 + 4 + EDGE_IDX[letter])
end

FT.CURTAIN_LETTER = {
	[IsoObjectType.curtainW] = "W", [IsoObjectType.curtainE] = "E",
	[IsoObjectType.curtainN] = "N", [IsoObjectType.curtainS] = "S",
}

-- The object's sprite name, nil when it has no sprite.
local function spriteName(obj)
	local sprite = obj:getSprite()
	return sprite and sprite:getName() or nil
end

-- An IsoCurtain wearing one of our sprites.
FT.isOurCurtain = function(obj)
	if not instanceof(obj, "IsoCurtain") then return false end
	local name = spriteName(obj)
	return name ~= nil and luautils.stringStarts(name, FT.TILESET .. "_")
end

-- An IsoCurtain wearing one of the vanilla WINDOW SHEET sprites
-- (fixtures_windows_curtains_01: 16..19 closed W/E/N/S, 20..23 open).
-- The moveable fabric-curtain furniture in the same tileset (0..15,
-- 24..95) is deliberately NOT matched - only sheets get re-skinned.
local VANILLA_SHEET = {}
for i = 16, 23 do
	VANILLA_SHEET["fixtures_windows_curtains_01_" .. i] = true
end

FT.isVanillaSheet = function(obj)
	if not instanceof(obj, "IsoCurtain") then return false end
	local name = spriteName(obj)
	return name ~= nil and VANILLA_SHEET[name] == true
end

-- Size class (0-based) for the window's CURRENT sprite, with every
-- open/smashed/glass-removed state mapped to its closed sprite's class.
-- nil for anything the vanilla half-tile sheet already covers, and for
-- the handful of panes no one-cell sheet can cover (see the skipped
-- list in the build).
FT.windowClass = function(obj)
	local name = spriteName(obj)
	return name and FT.MAP[name] or nil
end

-- Rows a sheet's body may stop short of the glass, or run past it onto
-- an overlay band, and still count as fitting: vanilla's own sheet
-- overlaps sills and frames by about this much.
FT.CLIP_TOL = 12

-- Names of every overlay sprite on the window's square: the attached
-- sprites of every object there (the cell loader hangs a WallOverlay on
-- the wall, the window or a garage door, whichever it finds first) and,
-- for a square with nothing to hang it on, the plain object it becomes.
local function squareOverlays(sq)
	local names = {}
	local objects = sq:getObjects()
	for i = 0, objects:size() - 1 do
		local obj = objects:get(i)
		local sprite = obj:getSprite()
		local name = sprite and sprite:getName()
		if name and FT.OVERLAYS[name] then names[name] = true end
		local attached = obj:getAttachedAnimSprite()
		if attached then
			for j = 0, attached:size() - 1 do
				local inst = attached:get(j)
				name = inst and inst:getName()
				if name and FT.OVERLAYS[name] then names[name] = true end
			end
		end
	end
	return names
end

-- The class to hang on this window: its mapped class, or - when solid
-- overlay bands on its square hide the top or bottom of its glass - the
-- largest class in the same column that fits the glass left showing.
-- nil exactly when FT.windowClass is nil.
FT.sheetClass = function(window)
	local base = FT.windowClass(window)
	if base == nil then return nil end
	local box = FT.CLASSES[base]
	local sq = window:getSquare()
	if not box or box.stack ~= "" or not sq then return base end
	local face = window:getNorth() and "N" or "W"
	local top, bottom = box.top, box.bottom
	for name in pairs(squareOverlays(sq)) do
		local band = FT.OVERLAYS[name]
		if band.face == face then
			if band.top and band.top > top then top = band.top end
			if band.bottom and band.bottom < bottom then bottom = band.bottom end
		end
	end
	if top - box.top <= FT.CLIP_TOL and box.bottom - bottom <= FT.CLIP_TOL then
		return base
	end
	local best, bestLen
	for c = 0, FT.N_CLASSES - 1 do
		local cb = FT.CLASSES[c]
		if cb.x == box.x and cb.stack == "" and cb.top >= top - FT.CLIP_TOL
				and cb.bottom <= bottom + FT.CLIP_TOL then
			local len = cb.bottom - cb.top
			if not best or len > bestLen then best, bestLen = c, len end
		end
	end
	return best or base
end

-- The far-side square of a window's edge: north edge -> y-1, west -> x-1.
-- May be nil (unloaded / world edge).
FT.farSquare = function(sq, north)
	if north then
		return getCell():getGridSquare(sq:getX(), sq:getY() - 1, sq:getZ())
	end
	return getCell():getGridSquare(sq:getX() - 1, sq:getY(), sq:getZ())
end

-- The two curtain slots of an edge: the near slot (curtainN/W on the
-- object's own square) and the far slot (curtainS/E on the neighbouring
-- square; nil when that square is unloaded).
FT.edgeCurtains = function(sq, north)
	local near = sq:getCurtain(north and IsoObjectType.curtainN or IsoObjectType.curtainW)
	local far = FT.farSquare(sq, north)
	local farCurtain = far and far:getCurtain(north and IsoObjectType.curtainS or IsoObjectType.curtainE)
	return near, farCurtain
end

-- -------------------------------------------------------------- order

-- B42 draws a square's translucent objects - the window, its curtain,
-- and nearly all furniture (vanilla's tileGeometry.txt marks a low
-- bookcase, a television, a radio, a crate Translucent, as it does the
-- curtain tiles) - in a pass of their own after the opaque one, with
-- depth WRITES off (FBORenderCell.renderOneChunk_Translucent:
-- glDepthMask(false)). Each is depth-tested against the opaque scene
-- only; between two translucent objects on one square the one later
-- in the square's object list paints over the earlier, whatever their
-- depth textures say. Vanilla's IsoWindow.addSheet appends the curtain
-- (AddSpecialTileObject = AddSpecialObject(obj, -1)), so a sheet paints
-- over everything on its square placed before it. The half-tile
-- vanilla sheet ends near the sill, where little stands; a fitted
-- sheet runs to the floor line and covered the TV on the low bookcase
-- in front of the window, the radio on the next one, the crate stack.
--
-- On the window's own square (the near slot, curtainW/N) everything
-- but the wall and the window is in FRONT of the wall plane, so the
-- sheet goes straight after the window - and after any barricade
-- nailed to it (IsoBarricade.AddBarricadeToObject puts a new barricade
-- in front of the facing's curtain, so the sheet paints over the
-- planks, as in vanilla). The far slot (curtainE/S, the square beyond
-- the wall) keeps vanilla's append: everything on that square is
-- behind the wall plane, and the sheet is the nearest thing to the
-- camera there.
--
-- The list's order is what saves and what MP packets address objects
-- by (RemoveItemFromSquarePacket: square plus index), so the move is
-- made where every copy of the square follows: in singleplayer, and on
-- the MP server BEFORE the sheet is transmitted - AddItemToMap carries
-- the object's index (IsoObject.writeToRemoteBuffer) and the client
-- inserts it there (loadFromRemoteBuffer) - while a square streaming to
-- a client arrives in the server's order. Sheets fitted by earlier
-- versions were appended like vanilla's; FT.reskinWindowSheets moves
-- them as their square loads (the LoadGridsquare sweep, SP/server).

local function indexIn(objects, obj)
	for i = 0, objects:size() - 1 do
		if objects:get(i) == obj then return i end
	end
	return -1
end

-- Move the object at `from` to `to` (indices of the object list),
-- shifting the ones between - with set() alone: PZArrayList's add and
-- remove are each overloaded on an index and an object, set is not.
local function moveObject(objects, from, to)
	local obj = objects:get(from)
	if from < to then
		for i = from, to - 1 do objects:set(i, objects:get(i + 1)) end
	else
		for i = from, to + 1, -1 do objects:set(i, objects:get(i - 1)) end
	end
	objects:set(to, obj)
end

-- Put a near-slot sheet straight after its window in the square's
-- object list, behind any barricade on that window. Nothing for a
-- sheet on another square (the far slot) or a window missing from the
-- list. Returns true when the sheet moved.
FT.orderNear = function(curtain, window)
	local sq = curtain:getSquare()
	if not sq or window:getSquare() ~= sq then return false end
	local objects = sq:getObjects()
	local at = indexIn(objects, window)
	if at < 0 then return false end
	local want = at + 1
	while want < objects:size() do
		local obj = objects:get(want)
		if not (instanceof(obj, "IsoBarricade") and obj:getBarricadedObject() == window) then break end
		want = want + 1
	end
	local from = indexIn(objects, curtain)
	if from < 0 then return false end
	-- taken out from before the slot, it shifts the slot down by one
	if from < want then want = want - 1 end
	if from == want then return false end
	moveObject(objects, from, want)
	return true
end

-- ------------------------------------------------------------- re-skin

-- Create the fitted curtain on the target square in the given open/closed
-- state. AddSpecialTileObject handles RecalcAllWithNeighbours, the LosUtil
-- cache and light recalc. Always hand the constructor the OPEN sprite:
-- closed resolves as open index - 4, and the constructor starts every
-- curtain open, so a closed sheet needs one ToggleDoorSilent (which flips
-- the sprite, clears the LOS cache and syncs). The state is set, and the
-- sheet moved to its place after the window (FT.orderNear), BEFORE the
-- transmit so MP clients receive the finished object, at its final
-- index, in one packet: the toggle's own sync packet is keyed by an
-- object index the clients do not hold yet and is dropped with a warn
-- line, while AddItemToMap and SyncIsoObject travel on different
-- channels with no ordering guarantee, so transmitting first would let
-- a reordered sync leave the client's copy open.
FT.placeCurtain = function(target, openSprite, north, open, window)
	local curtain = IsoCurtain.new(getCell(), target, openSprite, north)
	target:AddSpecialTileObject(curtain)
	if curtain:IsOpen() ~= (open == true) then curtain:ToggleDoorSilent() end
	if window then FT.orderNear(curtain, window) end
	target:invalidateVispolyChunkLevel()
	if isServer() then curtain:transmitCompleteItemToClients() end
	return curtain
end

-- Replace one vanilla sheet with the fitted sprite, keeping its slot
-- (side + curtain type) and open/closed state. SP and server only - the
-- callers guard isClient(): a client swapping its local copy would send
-- the server its own removal request and race the server's swap; clients
-- instead receive the server's remove + place transmits. Returns the
-- replacement, or nil when nothing was done.
FT.reskin = function(curtain, window)
	local class = FT.sheetClass(window)
	if class == nil then return nil end
	local target = curtain:getSquare()
	local letter = FT.CURTAIN_LETTER[curtain:getType()]
	if not target or not letter then return nil end
	-- the slot must still hold this exact curtain: a sheet reached twice
	-- (from both ends of its edge) is re-skinned once and skipped the
	-- second time, when the slot already holds the fitted replacement
	if target:getCurtain(curtain:getType()) ~= curtain then return nil end
	local wasOpen = curtain:IsOpen()
	target:transmitRemoveItemFromSquare(curtain)
	return FT.placeCurtain(target, FT.openSprite(class, letter), window:getNorth(), wasOpen, window)
end

-- Re-skin any vanilla sheet hanging on this window's edge, wherever
-- vanilla chose to put it: the near slot (curtainN/W on the window's own
-- square) or the far slot (curtainS/E on the neighbouring square), and
-- put an already-fitted near-slot sheet in its place after the window
-- (one fitted by an earlier version hangs at the end of the list, as
-- vanilla's would). Safe to call whenever - windows without a class,
-- without a sheet, or with a fitted sheet already in place are no-ops.
FT.reskinWindowSheets = function(window)
	if FT.windowClass(window) == nil then return end
	local sq = window:getSquare()
	if not sq then return end
	local north = window:getNorth()
	local near, farCurtain = FT.edgeCurtains(sq, north)
	if FT.isVanillaSheet(near) then
		FT.reskin(near, window)
	elseif FT.isOurCurtain(near) then
		FT.orderNear(near, window)
	end
	if FT.isVanillaSheet(farCurtain) then FT.reskin(farCurtain, window) end
end
